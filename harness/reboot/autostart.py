"""Re-launch pytest automatically after a reboot.

When a run contains reboot tests, the harness installs a **systemd user unit**
for the GUI user.  The unit starts after the graphical session comes back (the
autologin configured by :mod:`harness.reboot.session`), waits for the Wayland
or X11 socket, and then runs pytest again against the same artifact directory.

The wrapper script lives inside the run directory, so a run is self-contained
and can be inspected or removed afterwards.  Attempts are capped to avoid an
endless reboot loop if a test keeps failing.
"""

from __future__ import annotations

import os
import pwd
import shlex
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from .helper import HELPER_PATH, UNIT_FILE_NAME, priv_cleanup_unit
from .recovery import RESUME_GAVE_UP_NAME

__all__ = [
    "ResumePlan",
    "build_pytest_args",
    "build_resume_script",
    "install_resume_unit",
    "remove_resume_unit",
    "unit_path_for",
    "wants_path_for",
]

# Single source of truth: the privileged helper allowlists unit removal by name.
UNIT_NAME = UNIT_FILE_NAME
# Each attempt is a full boot; 12 covers legitimate multi-boot runs with room
# to spare while keeping a broken loop short.  (The attempt count lives in the
# generated script's ``resume/attempts`` file, maintained by that wrapper
# script alone.)
MAX_ATTEMPTS = 12


@dataclass(frozen=True)
class ResumePlan:
    installed: bool
    unit_path: Path | None = None
    script_path: Path | None = None
    reason: str = ""


def unit_path_for(username: str | None = None) -> Path:
    home = Path(pwd.getpwnam(username).pw_dir) if username else Path.home()
    return home / ".config" / "systemd" / "user" / UNIT_NAME


def wants_path_for(username: str | None = None) -> Path:
    """The ``enable`` symlink ``systemctl --user enable`` creates for the unit."""
    return unit_path_for(username).parent / "graphical-session.target.wants" / UNIT_NAME


def build_pytest_args(argv: list[str] | None = None) -> list[str]:
    """Strip any previous ``--resume-run`` option from the pytest arguments."""
    args = list(sys.argv[1:] if argv is None else argv)
    cleaned: list[str] = []
    skip_next = False
    for arg in args:
        if skip_next:
            skip_next = False
            continue
        if arg == "--resume-run":
            skip_next = True
            continue
        if arg.startswith("--resume-run="):
            continue
        cleaned.append(arg)
    return cleaned


def build_resume_script(
    run_dir: Path | str,
    *,
    pytest_args: list[str],
    workdir: Path | str | None = None,
    python: str | None = None,
    username: str | None = None,
    max_attempts: int = MAX_ATTEMPTS,
) -> str:
    """Render the shell wrapper that the systemd unit executes."""
    run_dir = Path(run_dir)
    workdir = Path(workdir) if workdir is not None else Path.cwd()
    python = python or sys.executable or "python3"
    command = " ".join(
        [shlex.quote(python), "-m", "pytest", *[shlex.quote(arg) for arg in pytest_args]]
    )
    attempts_file = Path(run_dir) / "resume" / "attempts"
    quoted_run_dir = shlex.quote(str(run_dir))
    quoted_attempts = shlex.quote(str(attempts_file))
    quoted_workdir = shlex.quote(str(workdir))
    quoted_helper = shlex.quote(str(HELPER_PATH))

    user_setup = ""
    if username:
        # f-string: {shlex.quote(username)} is substituted and the {{ }}
        # escapes render as single awk/shell braces (this block was long a
        # plain string, which emitted the placeholders verbatim and made the
        # unquoted parens in {shlex.quote(...)} a dash parse error that
        # killed every resumed boot before pytest could restart).
        user_setup = f"""
# Best-effort: wait for the graphical session that autologin started.
SESSION_ID=$(loginctl list-sessions --no-legend 2>/dev/null | awk -v u={shlex.quote(username)} '$3 == u {{ print $1; exit }}')
if [ -n "$SESSION_ID" ]; then
    # Assign/extend then export separately: the old `VAR=$(cmd) && export VAR`
    # chain silently skipped the export when loginctl printed nothing, leaving
    # _desktop_kind() blind and every idle/lock key untouched.
    if [ -z "${{XDG_SESSION_TYPE:-}}" ]; then
        XDG_SESSION_TYPE=$(loginctl show-session "$SESSION_ID" -p Type --value 2>/dev/null)
        export XDG_SESSION_TYPE
    fi
    if [ -z "${{XDG_CURRENT_DESKTOP:-}}" ]; then
        XDG_CURRENT_DESKTOP=$(loginctl show-session "$SESSION_ID" -p Desktop --value 2>/dev/null)
        export XDG_CURRENT_DESKTOP
    fi
fi
"""

    return f"""#!/bin/sh
# Generated by the GUI test harness.  Re-runs pytest after a reboot so a
# multi-boot run can continue where it stopped.  Delete the systemd unit and
# this file when the run is finished.
set -u

export GUI_TESTING_RESUME_RUN={quoted_run_dir}
export GUI_TESTING_RESUMED=1
export RUN_DESTRUCTIVE_TESTS=1
export GUI_TESTING_AUTOSTART=1
export GUI_TESTING_SETUP_DONE=1
export GUI_TESTING_PRIVILEGED_HELPER={quoted_helper}

LOG_FILE={quoted_run_dir}/resume/pytest-output.log
mkdir -p {quoted_run_dir}/resume

if [ -z "${{XDG_RUNTIME_DIR:-}}" ]; then
    XDG_RUNTIME_DIR="/run/user/$(id -u)"
    export XDG_RUNTIME_DIR
fi
if [ -z "${{DBUS_SESSION_BUS_ADDRESS:-}}" ] && [ -S "$XDG_RUNTIME_DIR/bus" ]; then
    DBUS_SESSION_BUS_ADDRESS="unix:path=$XDG_RUNTIME_DIR/bus"
    export DBUS_SESSION_BUS_ADDRESS
fi
{user_setup}
# Wait for a compositor socket (up to 120s); the unit can start a little early.
i=0
while [ "$i" -lt 120 ]; do
    if [ -z "${{WAYLAND_DISPLAY:-}}" ]; then
        for socket in "$XDG_RUNTIME_DIR"/wayland-*; do
            if [ -S "$socket" ]; then
                WAYLAND_DISPLAY=$(basename "$socket")
                export WAYLAND_DISPLAY
                break
            fi
        done
    fi
    [ -n "${{WAYLAND_DISPLAY:-}}" ] && break
    [ -n "${{DISPLAY:-}}" ] && break
    i=$((i + 1))
    sleep 1
done
if [ ! -S "$XDG_RUNTIME_DIR/${{WAYLAND_DISPLAY:-wayland-0}}" ] && [ -z "${{DISPLAY:-}}" ]; then
    echo "no graphical session available; giving up" >&2
    systemctl --user disable {UNIT_NAME} >/dev/null 2>&1 || true
    exit 1
fi

# Re-apply idle/lock protection BEFORE pytest starts: between autologin and
# pytest_configure the desktop policy would otherwise blank/lock the screen
# mid-run and every later GUI capture would fail.  State saving is idempotent
# (the pre-reboot idle_state.json already holds the originals).
if [ -d {quoted_workdir} ]; then
    cd {quoted_workdir}
    if [ -f .venv/bin/python ]; then
        . .venv/bin/activate 2>/dev/null || true
    fi
    python3 -c "from harness.reboot.idle import save_idle_state, disable_idle; save_idle_state(); r = disable_idle(); print('[idle] pre-pytest: applied', len(r['applied']), 'readback_ok', r['readback_ok']); [print('[idle] pre-pytest ERROR:', e) for e in r['errors']]" 2>&1 | tee -a "$LOG_FILE" || true
fi

# Do NOT open a terminal window during the run — it can cover the screen
# and interfere with GUI automation (screenshots, clicks).
# Progress is logged to $LOG_FILE and a desktop notification is shown.

# Show a desktop notification with the log path (best-effort)
if command -v notify-send >/dev/null 2>&1; then
    notify-send "GUI Testing" "Resuming pytest run.\nLog: $LOG_FILE" >/dev/null 2>&1 &
fi

ATTEMPTS=$(cat {quoted_attempts} 2>/dev/null || echo 0)
ATTEMPTS=$((ATTEMPTS + 1))
echo "$ATTEMPTS" > {quoted_attempts}
if [ "$ATTEMPTS" -gt {max_attempts} ]; then
    echo "resume attempt limit reached ($ATTEMPTS > {max_attempts}); giving up" >&2
    echo "RESUME LIMIT REACHED: this boot will idle (please intervene)" | tee -a "$LOG_FILE" >&2
    : > {quoted_run_dir}/resume/{RESUME_GAVE_UP_NAME}
    if command -v notify-send >/dev/null 2>&1; then
        notify-send -u critical "GUI Testing" "Resume attempt limit reached — run gave up." >/dev/null 2>&1 || true
    fi
    systemctl --user disable {UNIT_NAME} >/dev/null 2>&1 || true
    exit 1
fi

cd {quoted_workdir}
echo "=== Resuming pytest run: {quoted_run_dir} ===" | tee -a "$LOG_FILE"
echo "Started at: $(date)" | tee -a "$LOG_FILE"
echo "Attempt $ATTEMPTS of max {max_attempts}" | tee -a "$LOG_FILE"
# Append directly instead of piping through tee: PIPESTATUS is a bashism, and
# this script runs under /bin/sh (dash on Ubuntu), where the substitution is a
# fatal error that skipped the disable below and re-armed the unit every boot.
# systemd already sends the unit's output to the journal (journalctl --user).
{command} -s --resume-run {quoted_run_dir} >>"$LOG_FILE" 2>&1
status=$?
# One parameter set per reboot: do not start again on the next boot.
systemctl --user disable {UNIT_NAME} >/dev/null 2>&1 || true
exit "$status"
"""


def _systemctl_user(args: list[str], username: str | None = None) -> subprocess.CompletedProcess[str] | None:
    try:
        env = os.environ.copy()
        if username:
            try:
                entry = pwd.getpwnam(username)
                env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{entry.pw_uid}")
                env.setdefault("DBUS_SESSION_BUS_ADDRESS", f"unix:path=/run/user/{entry.pw_uid}/bus")
            except KeyError:
                pass
        return subprocess.run(
            ["systemctl", "--user", *args],
            capture_output=True, text=True, timeout=5, env=env,
        )
    except (OSError, subprocess.SubprocessError):
        return None


def _write_as_user(path: Path, text: str, username: str | None, *, mode: int = 0o644) -> bool:
    path = Path(path)
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        path.chmod(mode)
        return True
    except (OSError, KeyError):
        return False


def install_resume_unit(
    run_dir: Path | str,
    *,
    username: str | None = None,
    pytest_args: list[str] | None = None,
    workdir: Path | str | None = None,
    python: str | None = None,
    max_attempts: int = MAX_ATTEMPTS,
) -> ResumePlan:
    """Install and enable the resume unit for the GUI user."""
    run_dir = Path(run_dir)
    target_user = username or pwd.getpwuid(os.getuid()).pw_name
    unit_path = unit_path_for(target_user)
    script_path = run_dir / "resume" / "resume.sh"
    script_path.parent.mkdir(parents=True, exist_ok=True)

    script = build_resume_script(
        run_dir,
        pytest_args=build_pytest_args(pytest_args),
        workdir=workdir,
        python=python,
        username=target_user,
        max_attempts=max_attempts,
    )
    if not _write_as_user(script_path, script, target_user, mode=0o755):
        return ResumePlan(False, unit_path, script_path, f"could not write {script_path}")

    unit = f"""[Unit]
Description=Resume GUI testing pytest run after reboot
After=graphical-session.target
PartOf=graphical-session.target

[Service]
Type=oneshot
Environment="XDG_RUNTIME_DIR=/run/user/%U"
Environment="DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/%U/bus"
ExecStart=/bin/sh {script_path}
TimeoutStartSec=infinity

[Install]
WantedBy=graphical-session.target
"""
    if not _write_as_user(unit_path, unit, target_user):
        return ResumePlan(False, unit_path, script_path, f"could not write {unit_path}")

    _systemctl_user(["daemon-reload"], target_user)
    enable_result = _systemctl_user(["enable", UNIT_NAME], target_user)
    if enable_result is None or enable_result.returncode != 0:
        reason = enable_result.stderr.strip() if enable_result is not None else "systemctl --user unavailable"
        return ResumePlan(False, unit_path, script_path, reason or "enable failed")
    return ResumePlan(True, unit_path, script_path)


def remove_resume_unit(*, username: str | None = None) -> bool:
    """Disable, stop, and delete the resume unit (best-effort, multiple paths)."""
    target_user = username or pwd.getpwuid(os.getuid()).pw_name
    # Collect all possible unit file locations.
    paths_to_try = [unit_path_for(target_user)]
    # Also try current user's home.
    try:
        paths_to_try.append(unit_path_for(pwd.getpwuid(os.getuid()).pw_name))
    except KeyError:
        pass
    # Deduplicate.
    seen = set()
    unique_paths = []
    for p in paths_to_try:
        if str(p) not in seen:
            seen.add(str(p))
            unique_paths.append(p)

    env = os.environ.copy()
    try:
        entry = pwd.getpwnam(target_user)
        env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{entry.pw_uid}")
        env.setdefault("DBUS_SESSION_BUS_ADDRESS", f"unix:path=/run/user/{entry.pw_uid}/bus")
    except KeyError:
        pass

    # Stop and disable (skip systemctl --user which can hang).
    # Just remove the unit files directly.
    pass

    # Remove unit files and their ``enable`` symlink (a bare unlink of the
    # unit file would leave the wants symlink dangling).
    removed_any = False
    for up in unique_paths:
        for path in (up, up.parent / "graphical-session.target.wants" / UNIT_NAME):
            try:
                path.unlink()
                removed_any = True
            except FileNotFoundError:
                pass
            except OSError:
                if priv_cleanup_unit(up):
                    removed_any = True

    # Daemon reload (skip - can hang, not critical for cleanup).
    pass

    return removed_any
